#!/usr/bin/env python3
"""Import the pinned official ProperKorean release; never imports game assets."""

import hashlib
import json
from pathlib import Path
import sys
import tomllib
import zipfile

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / "patches/src/main/resources/balatro/properkorean"
KOTLIN = ROOT / "patches/src/main/kotlin/app/edgewindow/patches/balatro"
ARCHIVE_SHA256 = "ddfe0eeb8dddf974641cd6507a7d50aca431bfeb044c1682a557502fdcad5cc7"


def kotlin_string(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def main():
    archive = Path(sys.argv[1])
    if hashlib.sha256(archive.read_bytes()).hexdigest() != ARCHIVE_SHA256:
        raise SystemExit("Expected the official ProperKorean v0.7.1 ZIP (SHA-256 mismatch)")
    RESOURCES.mkdir(parents=True, exist_ok=True)
    KOTLIN.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive) as source:
        for name in ("ko.lua", "NotoSansKR-Bold.ttf", "lovely.toml"):
            (RESOURCES / name).write_bytes(source.read(name))
        # Replace only the PC startup routine. Keep upstream grammar and credits.
        utils = source.read("utils.lua").decode().replace("\r\n", "\n")
        helpers = utils[utils.index("function get_josa_for_rank"):]
        (RESOURCES / "helpers.lua").write_text(helpers + "\n", encoding="utf-8")
        manifest = tomllib.loads(source.read("lovely.toml").decode())

    edits = []
    for entry in manifest["patches"]:
        if "pattern" not in entry:
            continue  # The helper is appended separately.
        edit = entry["pattern"]
        if "_infotip_object.config.set" in edit["pattern"]:
            continue  # Steamodded workaround; not needed on Android.
        payload = edit["payload"].strip("\n")
        if edit["target"] == "game.lua":
            payload = "apply_properkorean_android()"
        count = 5 if "DynaText({string =" in edit["pattern"] else 1
        values = [edit["target"], edit["pattern"], edit["position"], payload]
        edits.append("    LuaEdit(" + ", ".join(map(kotlin_string, values)) + f", {count}),")

    (KOTLIN / "ProperKoreanEdits.kt").write_text(
        "// Generated by scripts/import-properkorean.py from ProperKorean v0.7.1.\n"
        "// Android adaptation: startup hook; omit Steamodded achievement workaround.\n"
        "package app.edgewindow.patches.balatro\n\n"
        "internal val properKoreanEdits = listOf(\n" + "\n".join(edits) + "\n)\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
